package OperasiBilangan;

public class OperasiBilangan {
    // Atribut untuk menyimpan dua bilangan (bisa double agar fleksibel)
    public double bil1;
    public double bil2;

    // Method penjumlahan (asumsi dari tugas sebelumnya)
    public double hitungPenjumlahan() {
        return bil1 + bil2;
    }

    // Method pengurangan (asumsi dari tugas sebelumnya)
    public double hitungPengurangan() {
        return bil1 - bil2;
    }

    // 1. Method Perkalian Baru
    public double hitungPerkalian() {
        return bil1 * bil2;
    }

    // 2. Method Pembagian Baru (menggunakan double)
    public double hitungPembagian() {
        return bil1 / bil2;
    }
}
